"""interests_config.py — темы классификации и промпт (Interests-модуль).

MVP-слой ТЗ (этап 1): фиксированный набор тем, LLM выбирает из списка.
Поверх этого позже (этап 4 ТЗ) добавится семантический поиск по произвольным
интересам через Vector DB — структура slug/label это поддерживает.
"""

from __future__ import annotations

# Фиксированный список тем. Slug (ключ) — для БД/роутинга, подпись — для меню.
TOPICS: tuple[tuple[str, str], ...] = (
    ("crypto",      "₿ Крипта"),
    ("tech",        "💻 IT и технологии"),
    ("ai",          "🤖 Искусственный интеллект"),
    ("auto",        "🚗 Авто"),
    ("geopolitics", "🌍 Геополитика"),
    ("economy",     "📊 Экономика"),
    ("sport",       "⚽ Спорт"),
    ("medicine",    "⚕️ Медицина"),
    ("science",     "🔬 Наука"),
    ("culture",     "🎭 Культура"),
    ("society",     "👥 Общество"),
    ("incidents",   "🚨 Происшествия"),
    ("war",         "🪖 Война"),
    ("energy",      "⚡ Энергетика"),
    ("business",    "💼 Бизнес"),
)

TOPIC_LABELS: dict[str, str] = {slug: label for slug, label in TOPICS}
TOPIC_SLUGS: tuple[str, ...] = tuple(slug for slug, _ in TOPICS)


def topic_label(slug: str) -> str:
    return TOPIC_LABELS.get(slug, slug)


def all_topic_slugs() -> list[str]:
    return list(TOPIC_SLUGS)


