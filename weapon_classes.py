# Обратный индекс: keyword -> slug.
_KEYWORD_INDEX: dict[str, str] = {}
for cls in WEAPON_CLASSES:
    for kw in cls["keywords"]:
        _KEYWORD_INDEX[kw] = cls["slug"]

# Slug -> класс.
_BY_SLUG: dict[str, dict] = {cls["slug"]: cls for cls in WEAPON_CLASSES}


def classify_weapon(text: str) -> str:
    """Определить класс оружия по тексту. Возвращает slug класса.

    Проверяет классы в порядке WEAPON_CLASSES (от конкретного к общему).
    Возвращает slug первого совпавшего класса.
    Если НИЧЕГО не найдено — 'unknown' («Тип загрози уточнюється»).
    НИКОГДА не выдумываем тип — лучше «невідомо», чем ложная паника.
    """
    if not text:
        return "unknown"
    lowered = text.lower()
    # Отбой — управляющее сообщение, а не ракетная угроза, даже если оно
    # упоминает завершившуюся «ракетную опасность».
    stand_down = _BY_SLUG["stand_down"]
    if any(contains_keyword(lowered, kw) for kw in stand_down["keywords"]):
        return "stand_down"
    for cls in WEAPON_CLASSES:
        if cls["slug"] == "stand_down":
            continue
        if any(contains_keyword(lowered, kw) for kw in cls["keywords"]):
            return cls["slug"]
    return "unknown"


def weapon_label(slug: str) -> str:
    """Нормализованное название класса по slug (красиво, не «мопед»)."""
    cls = _BY_SLUG.get(slug)
    if cls:
        return cls["label"]
    if slug == "unknown":
        return "❓ Тип загрози уточнюється"
    return slug


def weapon_eta(slug: str) -> str:
    """Типовое время подлёта по классу оружия."""
    cls = _BY_SLUG.get(slug)
    return cls["typical_eta"] if cls else "—"


def weapon_severity(slug: str) -> str:
    """Базовая критичность класса."""
    cls = _BY_SLUG.get(slug)
    return cls["severity"] if cls else "LOW"


def all_weapon_slugs() -> list[str]:
    """Список всех slug-ов классов оружия (включая 'unknown')."""
    return [cls["slug"] for cls in WEAPON_CLASSES] + ["unknown"]


def all_keywords() -> tuple[str, ...]:
    """Все ключевые слова всех классов — для первичного фильтра."""
    return tuple(_KEYWORD_INDEX.keys())
