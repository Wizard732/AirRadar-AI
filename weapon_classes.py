# Обратный индекс для быстрого поиска: keyword -> class_slug.
_KEYWORD_INDEX: dict[str, str] = {}
for cls in WEAPON_CLASSES:
    for kw in cls["keywords"]:
        _KEYWORD_INDEX[kw] = cls["slug"]

# Slug -> класс.
_BY_SLUG: dict[str, dict] = {cls["slug"]: cls for cls in WEAPON_CLASSES}


def classify_weapon(text: str) -> str:
    """Определить класс оружия по тексту. Возвращает slug класса.

    Проверяет классы в порядке WEAPON_CLASSES (от конкретного к общему).
    Возвращает slug первого совпавшего класса. Если ничего не найдено — 'other'.
    """
    if not text:
        return "other"
    lowered = text.lower()
    for cls in WEAPON_CLASSES:
        if any(kw in lowered for kw in cls["keywords"]):
            return cls["slug"]
    return "other"


def weapon_label(slug: str) -> str:
    """Человекочитаемое название класса по slug."""
    cls = _BY_SLUG.get(slug)
    return cls["label"] if cls else slug


def weapon_eta(slug: str) -> str:
    """Типовое время подлёта по классу оружия."""
    cls = _BY_SLUG.get(slug)
    return cls["typical_eta"] if cls else "—"


def weapon_severity(slug: str) -> str:
    """Базовая критичность класса."""
    cls = _BY_SLUG.get(slug)
    return cls["severity"] if cls else "MODERATE"


def all_weapon_slugs() -> list[str]:
    """Список всех slug-ов классов оружия."""
    return [cls["slug"] for cls in WEAPON_CLASSES]


# Ключевые слова для fast_filter — все из всех классов (плоский список).
def all_keywords() -> tuple[str, ...]:
    """Все ключевые слова всех классов — для первичного фильтра."""
    return tuple(_KEYWORD_INDEX.keys())
