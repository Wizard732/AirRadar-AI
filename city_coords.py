# Обратный индекс: ключ города -> slug города (строится один раз).
_CITY_KEY_INDEX: dict[str, str] = {}
for _slug, (_name, _region, _lat, _lon, _keys) in CITIES.items():
    for _kw in _keys:
        if _kw not in _CITY_KEY_INDEX:  # первый город с таким ключом выигрывает
            _CITY_KEY_INDEX[_kw] = _slug


def _haversine_km(a: tuple[float, float], b: tuple[float, float]) -> float:
    """Расстояние между двумя (lat, lon) в километрах."""
    lat1, lon1, lat2, lon2 = map(radians, (a[0], a[1], b[0], b[1]))
    dlat, dlon = lat2 - lat1, lon2 - lon1
    h = sin(dlat / 2) ** 2 + cos(lat1) * cos(lat2) * sin(dlon / 2) ** 2
    return 2 * 6371.0 * asin(sqrt(h))


def detect_city(text: str) -> str:
    """Slug города, упомянутого в тексте; самый конкретный (район > город).

    Совпадения сортируются по длине ключа: «Харків, Салтівка» даёт район
    Салтівка ('салтівк' длиннее 'харків'), а не центр Харкова.
    Сортировка стабильная: при равной длине побеждает первый в таблице.
    '' — ничего не найдено.
    """
    if not text:
        return ""
    lowered = text.lower()
    matches = [(kw, slug) for kw, slug in _CITY_KEY_INDEX.items() if kw in lowered]
    if not matches:
        return ""
    matches.sort(key=lambda pair: len(pair[0]), reverse=True)
    return matches[0][1]


def city_by_slug(slug: str) -> tuple[str, str, float, float] | None:
    """(название, область, lat, lon) по slug города; None если нет."""
    entry = CITIES.get(slug)
    if not entry:
        return None
    return entry[0], entry[1], entry[2], entry[3]


def nearest_place(lat: float, lon: float, max_km: float = 25.0) -> str:
    """Ближайшее место к точке: город (в пределах max_km) или область.

    Возвращает человекочитаемое название для подписи репорта геопозиции.
    """
    point = (lat, lon)
    best_city, best_km = "", float("inf")
    for slug, (name, _region, clat, clon, _keys) in CITIES.items():
        km = _haversine_km(point, (clat, clon))
        if km < best_km:
            best_city, best_km = name, km
    if best_km <= max_km:
        return best_city
    best_region, best_km = "", float("inf")
    for slug, (rlat, rlon) in REGION_CENTROIDS.items():
        km = _haversine_km(point, (rlat, rlon))
        if km < best_km:
            best_region, best_km = slug, km
    from regions import region_name  # локальный импорт: regions не зависит от этого модуля
    return region_name(best_region) if best_region else f"{lat:.3f}, {lon:.3f}"
