def matches_keywords(text: str) -> bool:
    """Вернуть True, если сообщение похоже на угрозу.

    Срабатывает, если:
      * есть прямое ключевое слово (``KEYWORDS``), либо
      * сработало контекстное правило (глагол движения + район/укрытие).
    НО отсекаются новости о СВЕРШИВШИХСЯ событиях (пострадал/погиб/вчера/после
    удара) через ``_NEGATIVE_MARKERS`` — это ретроспектива, не оперативная угроза.
    Джанк-посты (приветствия/реклама/донаты) блокируются ``_JUNK_MARKERS``,
    кроме сообщений, совпавших по KEYWORDS (отбой/ракеты не блокируем).
    Проверка регистронезависимая. Пустой текст трактуется как «не совпало».
    """
    if not text:
        return False
    lowered = text.lower()
    # Сначала проверяем анти-маркеры: если это новость о прошлом — пропускаем.
    if any(marker in lowered for marker in _NEGATIVE_MARKERS):
        return False
    if any(contains_keyword(lowered, keyword) for keyword in KEYWORDS):
        return True
    # Джанк-фильтр: ТОЛЬКО если нет совпадения по KEYWORDS (выше).
    if any(marker in lowered for marker in _JUNK_MARKERS):
        return False
    return _matches_context(lowered)


