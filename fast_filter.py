"""fast_filter.py — первичный отсев сообщений по ключевым словам.

Дёшевая проверка ДО тяжёлого запроса к Ollama, чтобы не гонять нейросеть на
нерелевантных постах. Двухуровневая:

1. Прямое совпадение по ``KEYWORDS`` (тип угрозы назван явно).
2. Контекстное правило ``_matches_context`` — короткие тревожные посты без
   явного слова, но с глаголом движения («летить!») и/или сигналом тревоги
   + район. Так ловим «Йде на Жуляни!» / «Дуже гучно у місті» без ложных
   срабатываний на обычные новости.
"""

from __future__ import annotations

# Ключевые слова первичного фильтра.
# Леммы в корневой форме — `in` сработает и на «вибух», и на «вибухи/вибухів».
KEYWORDS: tuple[str, ...] = (
    # --- общие / русские ---
    "ракет",          # ракета/ракеты/ракетной (корень покрывает формы RU+UA)
    "шахед",
    "бпла",
    "пуск",
    "взрыв",
    "тревога",
    "угроза",
    "каб",
    "дрон",
    "баллист",
    "кинжал",
    "пво",
    "отбой",
    "прилет",
    "миссил",
    # --- украинские (UA) ---
    "загроза",        # угроза
    "тривога",        # тревога
    "вибух",          # взрыв
    "відбій",         # отбой
    "літак",          # самолёт (часто «зліт літаків» — взлёт бомбардировщиков)
    "зліт",           # взлёт
    "удар",           # удар
    "попат",          # попадание
    "крил",           # крыло (иногда «крилаті ракети» без слова «ракета»)
    "міна",           # мина
    "авіа",           # авиаудар / авіація
    "противопов",     # противоповітряна оборона (ППО) — длинная форма
    "ппо",            # ПВО (украинская аббревиатура)
    # --- специфичные термины из реальных постов ---
    "бандерол",       # «бандеролі» — дроны-камикадзе «Бандероль»
    "циркон",         # ракета «Циркон»
    "балісти",        # балістика (укр.)
    "крилат",         # крилаті ракети (укр.) — крылатая ракета
    "лєт",            # «летить/летить!» — часто в коротких тревожных постах
    "летит",          # «летит!» (рус.)
    "укритт",         # «укриття!» — сигнал укрыться
    # английские/латиницей — встречаются в постах как есть
    "shahed",
    "missile",
    "strike",
)

# Глаголы движения / тревожные сигналы (только для контекстного правила).
_MOTION_SIGNALS: tuple[str, ...] = (
    "летит", "йд", "іде", "йдé",  # летит / идёт (RU+UA)
    "до вас", "на вас",           # «– до вас!» в коротких тревожных постах
    "гучно", "громко",            # «гучно у місті» / «громко»
    "куряться", "дим",            # «куряться» / «дым»
)

# Районы Киева и города-цели — если рядом с глаголом движения, это угроза.
_LOCATIONS: tuple[str, ...] = (
    # районы Киева
    "оболон", "печерськ", "голосіїв", "теремки", "луценз", "харківськ",
    "деснянськ", "дарниц", "святошин", "солом'янск", "соломянск", "шулявк",
    "подол", "видубичі", "бургомістр", "борщагівк", "троєщин", "республік",
    "українк", "касіан", "конча-засп", "жулення", "жуляни", "бровар",
    "вишневе", "ірпінь", "буча",
    # города-цели в постах
    "київ", "киев", "столиц", "лівий берег", "левый берег", "правий берег",
    "одеса", "одесса", "львів", "львов", "харків", "харьков", "дніпро",
    "днепр", "суми", "сумы", "чернігів", "житомир", "полтав", "конотоп",
    "славутич", "коростень", "народичі", "корюківк", "сновськ",
)


def _matches_context(lowered: str) -> bool:
    """Контекстное правило: глагол движения И (район ИЛИ сигнал «укрыться»).

    Ловит короткие тревожные посты вроде «Йде на Жуляни!» или «Лівий берег –
    укриття!», где нет явного названия типа угрозы, но есть направление удара.
    Возвращает False, если совпал только глагол без локации/укрытия — это
    отсекает ложные срабатывания на обычных новостях.
    """
    has_motion = any(sig in lowered for sig in _MOTION_SIGNALS)
    has_location = any(loc in lowered for loc in _LOCATIONS)
    has_shelter = "укритт" in lowered or "укрыти" in lowered
    return has_motion and (has_location or has_shelter)


def matches_keywords(text: str) -> bool:
    """Вернуть True, если сообщение похоже на угрозу.

    Срабатывает, если:
      * есть прямое ключевое слово (``KEYWORDS``), либо
      * сработало контекстное правило (глагол движения + район/укрытие).
    Проверка регистронезависимая. Пустой текст трактуется как «не совпало».
    """
    if not text:
        return False
    lowered = text.lower()
    if any(keyword in lowered for keyword in KEYWORDS):
        return True
    return _matches_context(lowered)
