# Разделитель перед подписью: стрелки/эмодзи/символы, после которых идёт призыв.
_LEAD_SEP = re.compile(r"\s*(?:➡|👉|👉🏻|↪|—|—)\s*")

# Markdown-ссылки на t.me в тексте поста: «[ Розвідка неба ](https://t.me/rozvidkaneba)».
# Это подписи/реклама канала-источника: в постах и на карте им не место.
_TME_MARKDOWN_RE = re.compile(
    r"\s*\[[^\]\n]{0,80}\]\(\s*(?:https?:)?//t\.me/[^\)\s]+\s*\)"
)
# Голые ссылки t.me (без markdown-обёртки).
_TME_URL_RE = re.compile(r"\s*(?:https?:)?//t\.me/\S+")

# Декоративные подписи-«вставки» вокруг имени канала: «✙ Розвідка неба ✙»,
# «✙✙» (остаток после вырезания ссылки). Внутри — до 60 символов без переносов.
_SIG_DECOR = "✙✠✞✜❖◆◇◈★☆✦✧†✝"
_DECORATED_SIG_RE = re.compile(
    rf"\s*[{_SIG_DECOR}]\s*[^\n]{{0,60}}?\s*[{_SIG_DECOR}]\s*"
)
# Обрывок подписи в самом конце текста: «✙[», «✙✙», «]» — хвост декоративной
# ссылки, обрезанный лимитом длины до имени канала. Строка, состоящая
# только из декора/скобок/пробелов после последнего переноса, — мусор.
_TAIL_RESIDUE_RE = re.compile(rf"\n[\s{_SIG_DECOR}\[\]{{}}()«»·—-]*$")


def _strip_channel_links(text: str) -> str:
    """Вырезать подписи канала: t.me-ссылки и декоративные вставки ✙…✙."""
    text = _TME_MARKDOWN_RE.sub(" ", text)
    text = _TME_URL_RE.sub(" ", text)
    # Пары декоративных символов убираем итеративно: «✙✙» после вырезания
    # ссылки — тоже подпись. Достаточно двух проходов.
    text = _DECORATED_SIG_RE.sub(" ", text)
    text = _DECORATED_SIG_RE.sub(" ", text)
    # Хвост-обрывок подписи («✙[», «✙✙») после последнего переноса — мусор.
    text = _TAIL_RESIDUE_RE.sub("", text)
    return text


def clean_signature(text: str) -> str:
    """Удалить хвост-подпись канала из текста сообщения.

    Каналы добавляют в конец поста спам вида
    «➡️Надіслати новину👉Підписатись:@channel» или декоративные вставки
    «✙ [ Розвідка неба ](https://t.me/rozvidkaneba) ✙». Эта подпись мешает
    дедупликации, засоряет сжатый текст и сбивает определение региона.
    Функция ищет типичный призыв-маркер и обрезает всё после него, затем
    вырезает t.me-ссылки и декоративные вставки с именем канала.
    """
    if not text:
        return text
    lowered = text.lower()
    cut_at = len(text)
    for marker in _SIGNATURE_MARKERS:
        idx = lowered.find(marker)
        if idx != -1 and idx < cut_at:
            cut_at = idx
    head = text[:cut_at]
    # Дополнительно отрезаем ведущие разделители (➡/👉), декор и скобки
    # оборванной markdown-ссылки перед маркером.
    if cut_at < len(text):
        head = _LEAD_SEP.sub("", head).rstrip(" \n\r\t➡👉›»|•[]()" + _SIG_DECOR).rstrip()
    cleaned = _strip_channel_links(head)
    # Схлопнуть пустые строки, оставшиеся после вырезанных подписей.
    cleaned = re.sub(r"[ \t]+\n", "\n", cleaned).strip()
    return cleaned if cleaned else head.strip()


