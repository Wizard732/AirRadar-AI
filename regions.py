def detect_kyiv_zone(text: str) -> str:
    """Определить берег Киева по тексту: 'kyiv_left' | 'kyiv_right' | ''.

    Совпадение по обоим берегам (или ни по одному) даёт '' — тогда рассылка
    идёт подписчикам обоих берегов.
    """
    if not text:
        return ""
    lowered = text.lower()
    left = any(kw in lowered for kw in _ZONE_KEYWORDS["kyiv_left"])
    right = any(kw in lowered for kw in _ZONE_KEYWORDS["kyiv_right"])
    if left and not right:
        return "kyiv_left"
    if right and not left:
        return "kyiv_right"
    return ""


def validate_city_for_regions(city: str, text: str, regions: list[str]) -> str:
    """Принять город лишь если он упомянут в посте и относится к его области."""
    candidate = city.strip().lower()
    lowered = text.lower()
    if not candidate or candidate not in lowered:
        return ""
    for slug in regions:
        if any(candidate == key or candidate in key for key in REGIONS.get(slug, ("", ()))[1]):
            return city.strip()
    return ""


def detect_region(text: str, channel: str = "") -> list[str]:
    """Вернуть список slug-ов регионов, упомянутых в тексте.

    Регистронезависимо. Возвращает уникальные slug-и в порядке первого
    совпадения. Один пост может дать несколько регионов (например,
    «БпЛА зі Сумської на Київ» → ['sumska', 'kyivska']).
    Пустой список = регион не определён.

    channel: @username или ID канала-источника. Если в тексте нет города,
    проверяем название канала (например @sumyliketop → Сумы).
    """
    if not text:
        return []
    lowered = text.lower()
    found: list[str] = []
    seen: set[str] = set()
    for kw, slug in _KEYWORD_INDEX.items():
        if kw in lowered and slug not in seen:
            found.append(slug)
            seen.add(slug)

    # Fallback: если регион не найден в тексте — пробуем по названию канала.
    if not found and channel:
        ch_lower = str(channel).lower()
        for ch_key, slug in _CHANNEL_REGION_MAP.items():
            if ch_key in ch_lower and slug not in seen:
                found.append(slug)
                seen.add(slug)
                break  # один регион по каналу

    return found


def region_name(slug: str) -> str:
    """Отображаемое имя региона по slug-у (для меню/сообщений)."""
    entry = REGIONS.get(slug)
    if entry:
        return entry[0]
    return ZONE_NAMES.get(slug, slug)  # fallback: Київ-зоны и неизвестные slug-и


def all_region_slugs() -> list[str]:
    """Список всех slug-ов регионов (для меню/пагинации)."""
    return list(REGIONS.keys())


def find_regions_by_text(query: str) -> list[str]:
    """Найти регионы/зоны по произвольному запросу (для /city в боте).

    Ищет по ключам регионов и Киев-зон в обе стороны (запрос в ключе или
    ключ в запросе), без учёта регистра. Ранжирование: точное совпадение
    ключа региона («дніпро» → Днепропетровская, а не район Киева) →
    зоны (конкретнее области) → остальные совпадения. Минимум 3 символа.
    """
    q = (query or "").strip().lower()
    if len(q) < 3:
        return []

    exact: list[str] = []       # точное равенство ключа региона
    zones: list[str] = []       # совпадения по Киев-зонам
    partial: list[str] = []     # остальные совпадения по регионам
    seen: set[str] = set()

    def _add(bucket: list[str], slug: str) -> None:
        if slug not in seen:
            seen.add(slug)
            bucket.append(slug)

    for zone, keys in _ZONE_KEYWORDS.items():
        if any(q in kw or kw in q for kw in keys):
            _add(zones, zone)
    for slug, (name, keys) in REGIONS.items():
        if q in name.lower():
            _add(exact, slug)
        elif any(kw == q for kw in keys):
            _add(exact, slug)
        elif any(q in kw or kw in q for kw in keys):
            _add(partial, slug)
    return exact + zones + partial
